function _wageningen_sum(T, J, P_D, Ae_Ao, Z)
    acc = T[1, 1] * J^T[1, 2] * P_D^T[1, 3] * Ae_Ao^T[1, 4] * Z^T[1, 5]
    for i in 2:size(T, 1)
        acc = acc + T[i, 1] * J^T[i, 2] * P_D^T[i, 3] * Ae_Ao^T[i, 4] * Z^T[i, 5]
    end
    return acc
end

