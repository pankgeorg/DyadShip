"""
    wageningen_4q_ct(model, beta)

Four-quadrant thrust coefficient `Ct(β)` of the Wageningen B-series propeller
`model` (a key of `WAGENINGEN_4Q`, e.g. `"B4_70_1"`) at hydrodynamic pitch
angle `beta` (rad) measured at 0.7 R.
"""
function wageningen_4q_ct(model::AbstractString, beta)
    T = WAGENINGEN_4Q[String(model)]
    acc = T[1, 2] * cos(T[1, 1] * beta) + T[1, 3] * sin(T[1, 1] * beta)
    for i in 2:size(T, 1)
        acc = acc + T[i, 2] * cos(T[i, 1] * beta) + T[i, 3] * sin(T[i, 1] * beta)
    end
    return acc / 100
end

"""
    wageningen_4q_cq(model, beta)

Four-quadrant torque coefficient `Cq(β)`; see `wageningen_4q_ct`.
"""
function wageningen_4q_cq(model::AbstractString, beta)
    T = WAGENINGEN_4Q[String(model)]
    acc = T[1, 4] * cos(T[1, 1] * beta) + T[1, 5] * sin(T[1, 1] * beta)
    for i in 2:size(T, 1)
        acc = acc + T[i, 4] * cos(T[i, 1] * beta) + T[i, 5] * sin(T[i, 1] * beta)
    end
    return -acc / 1000
end
