"""
    draft_poly(table, x)

Sum of `table[i, 1] * x^table[i, 2]` over the rows of `table`. This is the
regression form ShipSIM uses for every hydrostatic quantity (displacement,
LCB, VCB, BM, ...) as a function of mean draft `x`.
"""
function draft_poly(table::AbstractMatrix, x)
    acc = table[1, 1] * x^table[1, 2]
    for i in 2:size(table, 1)
        acc = acc + table[i, 1] * x^table[i, 2]
    end
    return acc
end

